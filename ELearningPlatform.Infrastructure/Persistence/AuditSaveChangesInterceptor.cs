using System.Reflection;
using System.Text.Json;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Diagnostics;

namespace ELearningPlatform.Infrastructure.Persistence;

/// <summary>
/// Writes an <see cref="AuditLog"/> row for every change to an <see cref="IAuditable"/> entity, in the same
/// SaveChanges (so in the same transaction) as the change itself: who, what, when, old and new values.
/// Modified rows record only the properties that changed.
/// </summary>
public sealed class AuditSaveChangesInterceptor(ICurrentUser currentUser, TimeProvider timeProvider) : SaveChangesInterceptor
{
    private static readonly JsonSerializerOptions JsonOptions = new() { WriteIndented = false };

    public override InterceptionResult<int> SavingChanges(DbContextEventData eventData, InterceptionResult<int> result)
    {
        AddAuditLogs(eventData.Context);
        return result;
    }

    public override ValueTask<InterceptionResult<int>> SavingChangesAsync(DbContextEventData eventData, InterceptionResult<int> result, CancellationToken cancellationToken = default)
    {
        AddAuditLogs(eventData.Context);
        return ValueTask.FromResult(result);
    }

    private void AddAuditLogs(DbContext? context)
    {
        if (context == null)
            return;

        var now = timeProvider.GetUtcNow().UtcDateTime;
        var logs = new List<AuditLog>();
        foreach (var entry in context.ChangeTracker.Entries<IAuditable>())
        {
            if (entry.State is not (EntityState.Added or EntityState.Modified or EntityState.Deleted))
                continue;

            // An id generated by the database isn't known yet; such rows are audited from their first change on
            var key = entry.Properties.Where(p => p.Metadata.IsPrimaryKey()).ToList();
            if (entry.State == EntityState.Added && key.Any(p => p.IsTemporary))
                continue;

            var properties = entry.Properties.Where(IsAudited).ToList();
            if (entry.State == EntityState.Modified)
            {
                properties = properties.Where(p => p.IsModified && !Equals(p.OriginalValue, p.CurrentValue)).ToList();
                if (properties.Count == 0)
                    continue;
            }

            logs.Add(new AuditLog
            {
                UserId = currentUser.UserId,
                Action = entry.State.ToString(),
                EntityType = entry.Metadata.ClrType.Name,
                EntityId = string.Join(",", key.Select(p => Convert.ToString(p.CurrentValue ?? p.OriginalValue, System.Globalization.CultureInfo.InvariantCulture))),
                OldValues = entry.State == EntityState.Added ? null : Serialize(properties, p => p.OriginalValue),
                NewValues = entry.State == EntityState.Deleted ? null : Serialize(properties, p => p.CurrentValue),
                IpAddress = currentUser.IpAddress,
                TraceId = currentUser.TraceId,
                Timestamp = now,
            });
        }

        if (logs.Count > 0)
            context.Set<AuditLog>().AddRange(logs);
    }

    private static bool IsAudited(PropertyEntry property)
        => property.Metadata.PropertyInfo?.GetCustomAttribute<NotAuditedAttribute>() == null;

    private static string Serialize(IEnumerable<PropertyEntry> properties, Func<PropertyEntry, object?> value)
        => JsonSerializer.Serialize(properties.ToDictionary(p => p.Metadata.Name, p => value(p) is Enum e ? e.ToString() : value(p)), JsonOptions);
}
